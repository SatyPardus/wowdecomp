// The central script manager: loads the compiled-in extensions, holds one ScriptRegistry<T> per
// script type and exposes one OnXxx(...) dispatcher per hook. The client calls a dispatcher at the
// matching seam; the dispatcher walks the registry of the hook's script type and calls the virtual
// on every script. Extensions never call a dispatcher, only the services: Log and the
// registration APIs (message handlers and sends, Lua functions and events, XML element types),
// which record what an extension adds and feed it to the client at the right seam.
class ExtensionMgr {
    friend class ScriptObject;

    private:
    ExtensionMgr();
    ~ExtensionMgr();

    public: /* Initialization */
    static ExtensionMgr* instance();

    // Opens Logs\Extensions.log and runs every compiled-in extension's entry point through the
    // table generated by Extensions/CMakeLists.txt. Each entry point instantiates its scripts,
    // whose constructors add them to their registry. No hook is fired here.
    void Initialize();

    // Deletes every registered script, empties the registries and closes the log.
    void Unload();

    void IncreaseScriptCount() { m_scriptCount++; }
    uint32_t GetScriptCount() const { return m_scriptCount; }

    // Writes one line to Logs\Extensions.log (flushed at once) and to the in-game console when the
    // console screen exists. The file is the record: console output is dropped before the console
    // font is loaded, which is the case for OnStartup.
    void Log(const char* format, ...);

    public: /* ConsoleScript */
    // Registration API. A console command (ConsoleCommandRegister; refused and logged when the
    // engine owns the name) usable from the console window and "/console <name> ..."; the
    // extension's commands are unregistered at Unload. A CVar (CVar::Register with the given
    // default, change callback, category and user pointer): the returned CVar* is the extension's
    // handle (m_intValue, m_floatValue, m_stringValue); Config.wtf values already loaded attach
    // to it. Both tables exist before the extensions load, so these apply at once from the entry
    // point or OnStartup.
    bool RegisterConsoleCommand(const char* name, COMMANDHANDLER handler, CATEGORY category, const char* help);
    void UnregisterConsoleCommand(const char* name);
    CVar* RegisterCVar(const char* name, const char* help, uint32_t flags, const char* defaultValue, ExtensionCVarCallback callback, CATEGORY category, void* arg = nullptr);

    void OnConsoleCommand(const char* command, const char* arguments);

    public: /* ClientScript */
    void OnStartup();
    void OnClientInitialized();
    void OnUpdate(float elapsedSec);
    void OnClientDestroy();
    void OnEnterWorld(uint32_t mapId);
    void OnLeaveWorld();
    void OnShutdown();

    public: /* WorldScript */
    void OnLoginVerifyWorld(uint32_t mapId, const C3Vector* position, float facing);
    void OnLogoutComplete();
    void OnMapLoaded(uint32_t mapId, const char* mapName);
    void OnMapUnload();
    void OnWorldUpdate(float elapsedSec);

    public: /* RenderScript */
    void OnFrameBegin(float elapsedSec);
    void OnWorldRendered();
    void OnFrameEnd();

    public: /* NetScript */
    // Registration API. A handler receives the server messages of one opcode that the stock
    // client has no handler for (the stock table always wins): it is the way to give the client
    // a new SMSG. opcode is the 16-bit wire opcode; it must not be one the stock client handles,
    // and the server has to send it, so an extension and its server module agree on a range the
    // stock protocol does not use (opcodes >= NUM_MSG_TYPES, 0x51F, are free of any stock
    // meaning). One handler per opcode; registering again replaces it.
    void RegisterMessageHandler(uint32_t opcode, ExtensionMessageHandler handler, void* param);
    void UnregisterMessageHandler(uint32_t opcode);

    // Builds a client message (32-bit opcode, then the payload bytes, the layout every stock
    // sender uses) and hands it to the current realm connection's Send. Returns false when there
    // is no connection to send on. The server has to know the opcode; a stock server drops or
    // refuses what it does not expect.
    bool SendClientMessage(uint32_t opcode, const void* payload, uint32_t bytes);
    bool SendClientMessage(uint32_t opcode, CDataStore& payload);

    void OnConnected(NetClient* client);
    void OnDisconnected(NetClient* client);
    void OnMessageReceived(NETMESSAGE msgId, uint32_t timeReceived, CDataStore* msg);
    // False when a script refused the message: the caller drops it instead of dispatching.
    bool CanMessageReceive(NETMESSAGE msgId, uint32_t timeReceived, CDataStore* msg);
    // True when a registered handler took the message; result is then the handler's return.
    bool DispatchRegisteredMessage(NETMESSAGE msgId, uint32_t timeReceived, CDataStore* msg, int32_t& result);
    void OnMessageSent(CDataStore* msg);

    public: /* ModelScript */
    void OnModelSharedLoaded(CM2Shared* shared);
    void OnModelSkinLoaded(CM2Shared* shared);
    void OnModelTexturesCreated(CM2Shared* shared);
    void OnModelSequenceLoaded(CM2Shared* shared, uint32_t sequenceIndex);
    void OnModelSharedDestroy(CM2Shared* shared);
    void OnModelCreated(CM2Model* model);
    void OnModelLoaded(CM2Model* model);
    void OnModelAnimated(CM2Model* model);
    void OnModelDestroy(CM2Model* model);

    public: /* UnitScript */
    void OnUnitMoveUpdate(CGUnit_C* unit, uint32_t time);
    void OnUnitDisplayInfoUpdated(CGUnit_C* unit);
    void OnUnitDeath(CGUnit_C* unit);
    void OnUnitAuraAdded(CGUnit_C* unit, uint32_t index, AuraData* aura, int32_t spellId);
    void OnUnitAuraRemoved(CGUnit_C* unit, uint32_t index, AuraData* aura, int32_t spellId);
    void OnUnitAuraEffectMaskUpdated(CGUnit_C* unit);
    void OnUnitWorldTransformUpdated(CGUnit_C* unit, float elapsed);
    void OnUnitMovementMessage(CGUnit_C* unit, uint32_t msgId, CDataStore* msg);

    public: /* UIScript */
    // Registration API: adds an XML element type (and CreateFrame type) backed by factory. Takes
    // effect when FrameXML's table exists (right after the engine's own types, or at once when
    // registered later); a name the engine already uses is refused and logged. unique makes the
    // type usable once, like <WorldFrame>.
    void RegisterXmlElement(const char* name, ExtensionFrameFactory factory, bool unique = false);

    // Client call after FrameXML_RegisterDefault: registers the recorded element types.
    void OnFrameXmlInitialized();

    void OnFrameCreated(CSimpleFrame* frame, XMLNode* node);
    void OnUnknownFrameType(const char* name, XMLNode* node);
    void OnFrameDestroyed(CSimpleFrame* frame);

    public: /* ObjectScript */
    void OnObjectCreated(CGObject_C* object);
    void OnObjectUpdate(CGObject_C* object, uint32_t time);
    void OnObjectRemoved(CGObject_C* object);
    void OnObjectDestroy(CGObject_C* object);
    void OnObjectSpellVisualKit(CGObject_C* object, const PlaySpellVisuaKitData* data);

    public: /* TerrainScript */
    void OnTerrainTileLoaded(CMapArea* area);
    void OnTerrainTileUnload(CMapArea* area);
    void OnTerrainChunkCreated(CMapChunk* chunk);
    void OnTerrainChunkPurge(CMapChunk* chunk);

    public: /* MapObjectScript */
    void OnMapObjLoaded(CMapObj* mapObj);
    void OnMapObjGroupLoaded(CMapObjGroup* group);

    public: /* TextureScript */
    void OnTextureCreated(CTexture* texture, const char* fileName);
    void OnTextureLoaded(CTexture* texture);

    public: /* AssetScript */
    // True when a script redirected the open: redirect then holds the substitute path.
    bool OnFileOpen(const char* name, char* redirect, uint32_t redirectSize);
    void OnFileOpened(const char* name, SFileImpl* file);

    public: /* ClientDBScript */
    void OnClientDBLoaded(WowClientDB_Base* db, const char* fileName);
    void OnClientDBInitialize();
    void OnClientDBShutdown();

    public: /* LuaScript */
    // Registration API. A function registered here is a global in every FrameScript state of the
    // contexts in the mask (FrameScriptContexts), registered through FrameScript_RegisterFunction
    // each time such a state is created and at once if one exists; it runs as engine code,
    // untainted, like every stock Script_* function. An event registered here is created in those
    // states together with the engine's events; GetFrameScriptEventIndex gives its index in the
    // current state for FrameScript_SignalEvent (UINT32_MAX when the current state does not have
    // it or no state exists). Both are recorded for the life of the client; register from the
    // extension's entry point or OnStartup.
    void RegisterLuaFunction(const char* name, lua_CFunction function, uint32_t contexts = FRAMESCRIPT_CONTEXTS_ALL);
    void RegisterFrameScriptEvent(const char* name, uint32_t contexts = FRAMESCRIPT_CONTEXTS_ALL);
    uint32_t GetFrameScriptEventIndex(const char* name);
    FrameScriptContext GetFrameScriptContext();

    // Registration API for a frame type's Lua methods (the piece a RegisterXmlElement type needs
    // to expose methods of its own). metatable is the type's static metatable reference, the one
    // its GetScriptMetaTable() override returns; registerMethods fills the method table the way
    // CGCooldown::RegisterScriptMethods does (the base type's RegisterScriptMethods first, then
    // FrameScript_Object::FillScriptMethodTable with its own FrameScript_Method array). The core
    // creates the table with FrameScript_Object::CreateScriptMetaTable in every state of the mask
    // (after the engine's own tables, before the LuaScript hooks) and resets the reference to
    // LUA_NOREF when the state is destroyed.
    void RegisterScriptMetaTable(int32_t* metatable, void (*registerMethods)(lua_State*), uint32_t contexts = FRAMESCRIPT_CONTEXTS_ALL);

    // Replaces the client's FrameScript_CreateEvents(names, count) call at each FrameScript rebuild
    // site. Registers the recorded functions and events for the context, fires
    // LuaScript::OnFrameScriptInitialized for every script (where they may declare more), then
    // creates the engine's names followed by the declared names in one FrameScript_CreateEvents
    // call, so the engine's indices are unchanged and the declared events get the indices
    // DeclareFrameScriptEvent returned.
    void OnFrameScriptInitialized(FrameScriptContext context, const char** names, uint32_t count);
    void OnFrameScriptDestroy(lua_State* L);

    // Service for LuaScript::OnFrameScriptInitialized only: returns the index name will have in the
    // event array being built, usable with FrameScript_SignalEvent once the hook has returned. An
    // engine event name returns the engine's index; a name declared twice returns the same index.
    // Outside the hook nothing is being built: the call is logged and returns UINT32_MAX.
    uint32_t DeclareFrameScriptEvent(const char* name);

    private:
    void ClearMessageHandlers();
    void ClearLuaRegistrations();
    void ClearXmlElements();
    void ClearConsoleRegistrations();

    uint32_t m_scriptCount;
};

#define sExtensionMgr ExtensionMgr::instance()

// One registry per script type. The script type's constructor calls AddScript(this) (see
// ScriptDefines/*.cpp), so an extension registers a script simply by instantiating it. The list is
// filled while ExtensionMgr::Initialize() runs the entry points and is read-only afterwards; the
// dispatchers iterate it in insertion order.
template <class TScript>
class ScriptRegistry {
    public:
    typedef std::vector<TScript*> ScriptVector;

    // The actual list of scripts, in registration order.
    static ScriptVector ScriptPointerList;

    static void AddScript(TScript* const script) {
        if (!script) {
            return;
        }

        ScriptPointerList.push_back(script);
        sExtensionMgr->IncreaseScriptCount();
    }

    static void Clear() {
        for (TScript* script : ScriptPointerList) {
            delete script;
        }

        ScriptPointerList.clear();
    }
};

template <class TScript>
typename ScriptRegistry<TScript>::ScriptVector ScriptRegistry<TScript>::ScriptPointerList;

#endif
