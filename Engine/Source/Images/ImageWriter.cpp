static int32_t ComputeLayout(uint32_t height, uint32_t width, uint32_t dataSize) {
    if (width == 800 && height == 600) {
        s_rects[0].x = -384;
        s_rects[0].width = 384;
        s_rects[0].y = -220;
        s_rects[0].height = 220;
        s_rects[1].x = 0;
        s_rects[1].width = 300;
        s_rects[1].y = -285;
        s_rects[1].height = 285;
        s_rects[2].x = -340;
        s_rects[2].width = 340;
        s_rects[2].y = 0;
        s_rects[2].height = 250;
        s_rects[3].x = 0;
        s_rects[3].width = 340;
        s_rects[3].y = 0;
        s_rects[3].height = 250;
        s_rectCount = 4;
        return SetBlockSize(4, 5, 2.5f) != 0;
    }

    int32_t unit = static_cast<int32_t>((height * 0.23255813953488372 + 4.0) * 0.2);
    int32_t rectHeight = unit * 5;
    int32_t bits = static_cast<int32_t>(s_encoder.GetEncodedSize(dataSize) * 8);
    int32_t columns = static_cast<int32_t>(static_cast<double>(bits) / unit) + 1;
    int32_t rectWidth = columns * 4;

    if (columns > static_cast<int32_t>(width)) {
        return 0;
    }

    if (2 * rectWidth >= static_cast<int32_t>(width - 16)) {
        int16_t x = static_cast<int16_t>(static_cast<int32_t>(rectWidth * -0.5f));
        s_rects[0].x = x;
        s_rects[0].width = static_cast<int16_t>(rectWidth);
        s_rects[0].y = static_cast<int16_t>(static_cast<int32_t>(rectHeight * -1.55f));
        s_rects[0].height = static_cast<int16_t>(rectHeight);
        s_rects[1].x = x;
        s_rects[1].width = static_cast<int16_t>(rectWidth);
        s_rects[1].y = static_cast<int16_t>(static_cast<int32_t>(rectHeight * -0.5f));
        s_rects[1].height = static_cast<int16_t>(rectHeight);
        s_rects[2].x = x;
        s_rects[2].width = static_cast<int16_t>(rectWidth);
        s_rects[2].y = static_cast<int16_t>(static_cast<int32_t>(rectHeight * 0.55f));
        s_rects[2].height = static_cast<int16_t>(rectHeight);
        s_rectCount = 3;
        return SetBlockSize(4, 5, 2.5f) != 0;
    }

    int32_t half = rectWidth >> 1;
    s_rects[0].y = static_cast<int16_t>(-(rectHeight >> 1));
    s_rects[0].x = static_cast<int16_t>(-half);
    s_rects[0].width = static_cast<int16_t>(rectWidth);
    s_rects[0].height = static_cast<int16_t>(rectHeight);
    uint32_t count = 1;
    s_rectCount = 1;
    int32_t halfWidth = static_cast<int32_t>(width >> 1);
    int32_t position = half;

    if (half + rectWidth + 4 < halfWidth) {
        do {
            if (count > 30) {
                break;
            }

            position += 4;
            int16_t y = static_cast<int16_t>(static_cast<int32_t>(rectHeight * -0.5f));
            s_rects[count].x = static_cast<int16_t>(position);
            s_rects[count].width = static_cast<int16_t>(rectWidth);
            s_rects[count].y = y;
            s_rects[count].height = static_cast<int16_t>(rectHeight);
            int32_t next = position + rectWidth;
            s_rects[count + 1].x = static_cast<int16_t>(-next);
            s_rects[count + 1].width = static_cast<int16_t>(rectWidth);
            s_rects[count + 1].y = y;
            s_rects[count + 1].height = static_cast<int16_t>(rectHeight);
            count += 2;
            position = next;
        } while (position + rectWidth + 4 < halfWidth);

        s_rectCount = count;
    }

    position = 0;
    int32_t extent = rectWidth + 4;

    if (extent < halfWidth) {
        do {
            if (count > 28) {
                break;
            }

            extent += 4;
            position += 4;
            int16_t upper = static_cast<int16_t>(-4 - static_cast<int32_t>(rectHeight * 1.5f));
            s_rects[count].x = static_cast<int16_t>(position);
            s_rects[count].width = static_cast<int16_t>(rectWidth);
            s_rects[count].y = upper;
            s_rects[count].height = static_cast<int16_t>(rectHeight);
            int16_t lower = static_cast<int16_t>(4 - static_cast<int32_t>(rectHeight * -0.5f));
            s_rects[count + 1].x = static_cast<int16_t>(position);
            s_rects[count + 1].width = static_cast<int16_t>(rectWidth);
            s_rects[count + 1].y = lower;
            s_rects[count + 1].height = static_cast<int16_t>(rectHeight);
            extent += rectWidth;
            position += rectWidth;
            s_rects[count + 2].x = static_cast<int16_t>(-position);
            s_rects[count + 2].width = static_cast<int16_t>(rectWidth);
            s_rects[count + 2].y = upper;
            s_rects[count + 2].height = static_cast<int16_t>(rectHeight);
            s_rects[count + 3].x = static_cast<int16_t>(-position);
            s_rects[count + 3].width = static_cast<int16_t>(rectWidth);
            s_rects[count + 3].y = lower;
            s_rects[count + 3].height = static_cast<int16_t>(rectHeight);
            count += 4;
        } while (extent < halfWidth);

        s_rectCount = count;
    }

    return SetBlockSize(4, 5, 2.5f) != 0;
}

