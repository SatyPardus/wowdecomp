static int32_t WriteJpegFile(IWJpegParams* params) {
    if (!params->m_pixels) {
        return 0;
    }

    struct jpeg_error_mgr jerr;
    struct jpeg_compress_struct cinfo;
    cinfo.err = jpeg_std_error(&jerr);
    jpeg_create_compress(&cinfo);

    if (cinfo.error_flag) {
        return 0;
    }

    jerr.addon_message_table = s_addonMessages;
    jerr.first_addon_message = 1000;
    jerr.last_addon_message = 1012;
    cinfo.in_color_space = JCS_RGB;
    jpeg_set_defaults(&cinfo);

    if (cinfo.error_flag) {
        return 0;
    }

    int32_t luminance[64];
    int32_t chrominance[64];
    uint32_t quality = params->m_quality;

    if (quality % 10) {
        const int32_t* luminanceHigh = s_luminanceTables[quality / 10];
        const int32_t* chrominanceHigh = s_chrominanceTables[quality / 10];
        const int32_t* luminanceLow = s_luminanceTables[quality / 10 - 1];
        const int32_t* chrominanceLow = s_chrominanceTables[quality / 10 - 1];

        if (quality > 50 && quality < 60) {
            luminanceLow = s_luminanceTables[10];
            chrominanceLow = s_chrominanceTables[10];
        }

        float fraction = (quality % 10) * 0.1f;

        for (int32_t i = 0; i < 64; i++) {
            luminance[i] = luminanceLow[i] + static_cast<uint32_t>((luminanceHigh[i] - luminanceLow[i]) * fraction);
            chrominance[i] = chrominanceLow[i] + static_cast<uint32_t>((chrominanceHigh[i] - chrominanceLow[i]) * fraction);
        }
    } else {
        for (int32_t i = 0; i < 64; i++) {
            luminance[i] = s_luminanceTables[quality / 10 - 1][i];
            chrominance[i] = s_chrominanceTables[quality / 10 - 1][i];
        }
    }

    jpeg_add_quant_table(&cinfo, 0, luminance, FALSE);

    if (cinfo.error_flag) {
        return 0;
    }

    jpeg_add_quant_table(&cinfo, 1, chrominance, FALSE);

    if (cinfo.error_flag) {
        return 0;
    }

    FILE* file = fopen(params->m_fileName, "wb");

    if (!file) {
        return 0;
    }

    cinfo.image_width = params->m_width;
    cinfo.image_height = params->m_height;
    cinfo.input_components = params->m_bytesPerPixel;
    cinfo.source_pixels = params->m_pixels;
    mem_source_ptr source = jinit_read_mem(&cinfo);

    if (cinfo.error_flag) {
        return 0;
    }

    source->input_file = nullptr;
    cinfo.input_components = 3;
    (*source->start_input)(&cinfo, source);

    if (cinfo.error_flag) {
        return 0;
    }

    jpeg_default_colorspace(&cinfo);

    if (cinfo.error_flag) {
        return 0;
    }

    if (params->m_subsample) {
        cinfo.comp_info[0].h_samp_factor = 2;
        cinfo.comp_info[0].v_samp_factor = 2;
    } else {
        cinfo.comp_info[0].h_samp_factor = 1;
        cinfo.comp_info[0].v_samp_factor = 1;
    }

    cinfo.comp_info[1].h_samp_factor = 1;
    cinfo.comp_info[1].v_samp_factor = 1;
    cinfo.comp_info[2].h_samp_factor = 1;
    cinfo.comp_info[2].v_samp_factor = 1;
    jpeg_stdio_dest(&cinfo, file);

    if (cinfo.error_flag) {
        return 0;
    }

    jpeg_start_compress(&cinfo, TRUE);

    if (cinfo.error_flag) {
        return 0;
    }

    if (params->m_comment) {
        jpeg_write_marker(&cinfo, JPEG_COM, reinterpret_cast<const JOCTET*>(params->m_comment), static_cast<uint32_t>(strlen(params->m_comment)));

        if (cinfo.error_flag) {
            return 0;
        }
    }

    while (cinfo.next_scanline < cinfo.image_height) {
        JDIMENSION rows = (*source->get_pixel_rows)(&cinfo, source);
        jpeg_write_scanlines(&cinfo, source->buffer, rows);

        if (cinfo.error_flag) {
            return 0;
        }
    }

    (*source->finish_input)(&cinfo, source);
    jpeg_finish_compress(&cinfo);

    if (cinfo.error_flag) {
        return 0;
    }

    jpeg_destroy_compress(&cinfo);

    if (cinfo.error_flag) {
        return 0;
    }

    if (file != stdout) {
        fclose(file);
    }

    return 1;
}

