static int32_t ValidateRects(IWRect** rects, uint32_t* count, uint32_t byteCount, uint32_t width, uint32_t height, bool checkCapacity) {
    s_defaultRect.x = static_cast<int16_t>(-static_cast<int32_t>(width >> 1));
    s_defaultRect.width = static_cast<int16_t>(width);
    s_defaultRect.y = static_cast<int16_t>(-static_cast<int32_t>(height >> 1));
    s_defaultRect.height = static_cast<int16_t>(height);

    if (!*rects || !*count) {
        *rects = &s_defaultRect;
        *count = 1;

        if (checkCapacity && 8 * byteCount > (s_defaultRect.height / s_blockHeight) * (s_defaultRect.width / s_blockWidth)) {
            return 0;
        }

        return 1;
    }

    for (uint32_t i = 0; i < *count; i++) {
        IWRect* rect = &(*rects)[i];

        if (rect->x < s_defaultRect.x || rect->x + rect->width > s_defaultRect.x + s_defaultRect.width || rect->y < s_defaultRect.y || rect->y + rect->height > s_defaultRect.y + s_defaultRect.height) {
            return 0;
        }

        for (uint32_t j = i + 1; j < *count; j++) {
            IWRect* other = &(*rects)[j];
            int32_t overlapX = 0;

            if (rect->x < other->x + other->width && other->x < rect->x + rect->width) {
                overlapX = 1;
            }

            if (rect->y < other->y + other->height && other->y < rect->y + rect->height && overlapX) {
                return 0;
            }
        }

        if (checkCapacity && 8 * byteCount > (rect->width / s_blockWidth) * (rect->height / s_blockHeight)) {
            return 0;
        }
    }

    return 1;
}

