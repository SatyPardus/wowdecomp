static int32_t EmbedBits(IWEmbedParams* params) {
    if (!params) {
        return 0;
    }

    if (params->m_width < 2 * s_blockWidth || params->m_height < 2 * s_blockHeight) {
        return 0;
    }

    if (!ValidateRects(&params->m_rects, &params->m_rectCount, params->m_byteCount, params->m_width, params->m_height, true)) {
        return 0;
    }

    const uint8_t* bits = params->m_bits;
    uint32_t maxIterations = 0;

    for (uint32_t r = 0; r < params->m_rectCount; r++) {
        IWRect* rect = &params->m_rects[r];
        uint32_t left = (params->m_width >> 1) + rect->x;
        uint32_t right = left + rect->width;
        uint32_t top = (params->m_height >> 1) + rect->y;
        uint32_t bottom = top + rect->height;
        uint32_t bitIndex = 0;

        for (uint32_t x = left; x < right; x += s_blockWidth) {
            for (uint32_t y = top; y < bottom; y += s_blockHeight) {
                float invArea = 1.0f / s_blockArea;
                float sum = 0.0f;
                int32_t saturated = 0;

                for (uint32_t py = y; py < y + s_blockHeight; py++) {
                    for (uint32_t px = x; px < x + s_blockWidth; px++) {
                        const uint8_t* pixel = params->m_pixels + (py * params->m_width + px) * params->m_bytesPerPixel;

                        if (255 - pixel[0] < s_step || 255 - pixel[1] < s_step || 255 - pixel[2] < s_step) {
                            saturated++;
                        }

                        sum += pixel[2] * 0.299f + pixel[0] * 0.114f + pixel[1] * 0.587f;
                    }
                }

                float mean = sum * invArea;
                float target = mean;

                if (bitIndex >> 3 < params->m_byteCount) {
                    if (bits[bitIndex >> 3] & (1 << (bitIndex & 7))) {
                        target = 0.5f * s_step + static_cast<int32_t>(mean / s_step) * s_step;
                    } else {
                        target = static_cast<int32_t>((0.5f * s_step + mean) / s_step) * s_step;
                    }

                    bitIndex++;
                }

                float difference = target - mean;

                if (fabs(difference) <= 0.0000099999997f) {
                    continue;
                }

                float level = AdjustBlock(y, params->m_width, params->m_pixels, params->m_bytesPerPixel, difference / mean, x);
                float invStep = 1.0f / s_step;
                float error = fabs(invStep * level - invStep * target);

                uint32_t iteration = 0;

                while (error > 0.02f && iteration < 16) {
                    iteration++;

                    if (iteration > maxIterations) {
                        maxIterations = iteration;
                    }

                    level = AdjustBlock(y, params->m_width, params->m_pixels, params->m_bytesPerPixel, (target - level) / level, x);
                    error = fabs(invStep * level - invStep * target);

                    if (iteration == 8 && saturated > static_cast<int32_t>(s_blockHeight * s_blockWidth * 0.68f)) {
                        target -= s_step;
                    }
                }

                SelectWeights();
            }
        }
    }

    return 1;
}

